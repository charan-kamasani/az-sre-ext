#!/usr/bin/env python3

"""Generate a deterministic CLI reference from loaded extension metadata.

This extension's _help.py (code generated by aaz-dev-tools) is empty --
every AAZCommand/AAZCommandGroup already carries its own help dict (see
`.help` below), and there is no single call that lazily loads every command
at once (custom.py recipes register unconditionally, but pure-generated
aaz/latest/app/... modules are still path-gated by load_aaz_command_table).
So PROBE_PATHS below enumerates one path per leaf command group to
force-load everything; add a new path here whenever a new top-level or
nested command group is
added to custom.py or the generated aaz/latest tree, or this reference will
silently omit it.
"""

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1] / "src" / "sre"
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

REFERENCE_PATH = Path("docs/cli-reference.md")
REGENERATION_COMMAND = "python3 scripts/generate_cli_reference.py"

# One path per leaf command group -- see module docstring for why this list
# is hand-maintained instead of derived from a help-entries dict.
PROBE_PATHS = (
    ["sre", "agent", "connector", "delete"],
    ["sre", "agent", "identity", "remove"],
    ["sre", "agent", "extension", "delete"],
    ["sre", "supported-agent-model", "list"],
)

GLOBAL_OPTIONS = (
    ("--debug", "Increase logging verbosity to show all debug logs."),
    ("--help, -h", "Show this help message and exit."),
    ("--only-show-errors", "Only show errors, suppressing warnings."),
    (
        "--output, -o",
        "Output format: json, jsonc, none, table, tsv, yaml, or yamlc.",
    ),
    ("--query", "JMESPath query string."),
    (
        "--subscription",
        "Subscription name or ID; otherwise use the active subscription.",
    ),
    ("--verbose", "Increase logging verbosity."),
)


@dataclass(frozen=True)
class Option:
    aliases: tuple
    kind: str
    required: bool
    default: str
    choices: tuple
    help: str
    takes_value: bool = True


def repository_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _deprecation(recipe):
    factory = getattr(recipe, "AZ_DEPRECATE_INFO", None)
    return dict(getattr(factory, "keywords", {})) if factory else {}


def _argument_kind(argument) -> str:
    name = type(argument).__name__
    if "Bool" in name:
        return "Boolean"
    if "Int" in name:
        return "Integer"
    if "List" in name:
        return "List"
    if "Dict" in name:
        return "Dictionary"
    if "Object" in name:
        return "Object"
    return "String"


def _format_default(value, undefined) -> str:
    if value == undefined:
        return ""
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, (dict, list)):
        return json.dumps(value, sort_keys=True, separators=(",", ":"))
    return str(value)


def _argument_options(command, undefined):
    options = []
    for argument in command.get_arguments_schema()._fields.values():
        if not getattr(argument, "_registered", False):
            continue
        aliases = tuple(getattr(argument, "_options", ()) or ())
        if not aliases:
            continue
        enum = getattr(argument, "enum", None)
        kind = _argument_kind(argument)
        is_no_wait = "--no-wait" in aliases
        if is_no_wait:
            kind = "Flag"
        choices = (
            ()
            if is_no_wait
            else (
                ("false", "true")
                if kind == "Boolean"
                else (tuple(str(value) for value in enum.to_choices()) if enum else ())
            )
        )
        default = getattr(argument, "_default", undefined)
        help_data = getattr(argument, "_help", {}) or {}
        options.append(
            Option(
                aliases=aliases,
                kind=kind,
                required=bool(getattr(argument, "_required", False) and default == undefined),
                default=_format_default(default, undefined),
                choices=choices,
                help=str(help_data.get("short-summary", "")),
                takes_value=not is_no_wait,
            )
        )
    registered_aliases = {alias for option in options for alias in option.aliases}
    if getattr(command, "supports_no_wait", False) and "--no-wait" not in registered_aliases:
        options.append(
            Option(
                aliases=("--no-wait",),
                kind="Flag",
                required=False,
                default="false",
                choices=(),
                help="Do not wait for the long-running operation to finish.",
                takes_value=False,
            )
        )
    if getattr(command, "confirmation", None) is not None:
        options.append(
            Option(
                aliases=("--yes", "-y"),
                kind="Flag",
                required=False,
                default="false",
                choices=(),
                help="Do not prompt for confirmation.",
                takes_value=False,
            )
        )
    return options


def _group_help_by_name():
    """Map AZ_NAME -> AZ_HELP for every AAZCommandGroup custom.py defines.

    commands.py only ever registers AAZCommand *instances* into
    loader.command_group_table (see its load_command_table -- there is no
    loop copying AAZCommandGroup subclasses in), so group docstrings
    written on e.g. '_AccessGroup'/'_ConnectorGroup' in custom.py are never
    visible to the real 'az sre access -h' help renderer through that
    table either -- they reach the CLI via a separate knack code path that
    reads AZ_HELP directly off the class. Mirror that here instead of
    relying on command_group_table, which is empty for every one of our
    hand-written top-level nouns.
    """
    import inspect

    from azure.cli.core.aaz import AAZCommandGroup

    from azext_sre import custom

    result = {
        value.AZ_NAME: (value.AZ_HELP or {})
        for value in vars(custom).values()
        if (
            inspect.isclass(value)
            and issubclass(value, AAZCommandGroup)
            and value is not AAZCommandGroup
            and getattr(value, "AZ_NAME", None)
            and value.__module__ == custom.__name__
        )
    }

    # The root "sre" group has no AAZCommandGroup subclass at all (it's the
    # implicit root everything else registers under) -- its summary lives
    # directly in _help.py's knack `helps['sre']` YAML string instead. Parse
    # it the same way knack itself does, so the reference and the real `az
    # sre -h` output can never show two different root summaries.
    import yaml

    from azext_sre._help import helps as knack_helps

    if "sre" in knack_helps:
        result["sre"] = yaml.safe_load(knack_helps["sre"]) or {}

    return result


def collect_reference():
    from azure.cli.core.aaz import AAZUndefined
    from azure.cli.core.mock import DummyCli

    from azext_sre import SreCommandsLoader

    loader = SreCommandsLoader(cli_ctx=DummyCli())
    for path in PROBE_PATHS:
        loader.load_command_table(path)

    commands = dict(loader.command_table)
    groups = dict(loader.command_group_table)
    custom_group_help = _group_help_by_name()
    # command_group_table only contains groups that were explicitly
    # registered with @register_command_group; derive the rest (e.g. "sre
    # agent extension", which only exists implicitly via its commands) so
    # every group still gets a section below, just without a summary line.
    for name in commands:
        parts = name.split(" ")
        for depth in range(1, len(parts)):
            prefix = " ".join(parts[:depth])
            groups.setdefault(prefix, None)

    public_commands = {
        name: command
        for name, command in commands.items()
        if not _deprecation(type(command)).get("hide")
    }
    public_groups = {
        name: group
        for name, group in groups.items()
        if not (group is not None and _deprecation(type(group)).get("hide"))
    }
    return {
        "commands": {
            name: {
                "help": command.help,
                "options": _argument_options(command, AAZUndefined),
            }
            for name, command in public_commands.items()
        },
        "groups": {
            name: {
                "help": custom_group_help.get(name)
                or (group.help if group is not None else None)
                or {}
            }
            for name, group in public_groups.items()
        },
    }


def _cell(value) -> str:
    return " ".join(str(value or "").split()).replace("|", "\\|")


def _primary_alias(option: Option) -> str:
    return next((alias for alias in option.aliases if alias.startswith("--")), option.aliases[0])


def _placeholder(option: Option) -> str:
    if not option.takes_value:
        return ""
    if option.choices:
        return " {" + ",".join(option.choices) + "}"
    return {
        "Boolean": " {false,true}",
        "Dictionary": " <json-or-@file>",
        "Integer": " <integer>",
        "List": " <json-or-@file>",
        "Object": " <json-or-@file>",
        "String": " <value>",
    }[option.kind]


def command_syntax(name: str, options) -> str:
    parts = [f"az {name}"]
    for option in options:
        fragment = _primary_alias(option) + _placeholder(option)
        parts.append(fragment if option.required else f"[{fragment}]")
    return " ".join(parts)


def _direct_children(parent: str, names):
    prefix = f"{parent} "
    return sorted(name for name in names if name.startswith(prefix) and " " not in name[len(prefix):])


def render_reference(reference=None) -> str:
    reference = reference or collect_reference()
    commands = reference["commands"]
    groups = reference["groups"]
    lines = [
        "<!--",
        "GENERATED FILE - DO NOT EDIT.",
        f"Regenerate with: {REGENERATION_COMMAND}",
        "-->",
        "",
        "# `az sre` CLI ergonomics reference",
        "",
        "> [!IMPORTANT]",
        "> This file is generated from the loaded extension command, help, and",
        "> argument metadata. Do not edit it manually. Regenerate it with",
        f"> `{REGENERATION_COMMAND}`.",
        "",
        f"Public surface: **{len(groups)} groups** and **{len(commands)} commands**.",
        "",
        "## Important caveats",
        "",
        "- This CLI only talks to the control plane (`Microsoft.App/agents` ARM "
        "resource). It never talks to the agent's own data plane "
        "(`*.azuresre.ai`) directly. See the [implementation plan](../PLAN.md).",
        "- The overall noun/verb shape (why `agent` isn't a wrapper for every "
        "other noun, why there's one dedicated noun per runbook-extension "
        "type instead of a generic `extension --type`) is a deliberate "
        "decision with alternatives considered -- see the "
        "[shape design doc](shape-design.md).",
        "- `network update` is hand-written against the real "
        "`2026-11-01-preview` api-version; there is no public Swagger for it "
        "yet. See the [networking guide](networking.md).",
        "- `--value` JSON documents (e.g. `tool create`, `skill create`, "
        "`agent settings update`) are base64-encoded and sent as-is to the "
        "agent's data plane. Each extension type has its own dedicated "
        "front-door noun (`tool`, `skill`, `hook`, `instructions`, "
        "`plugin marketplace`/`plugin install`, `repo connect`, "
        "`agent settings`); there is no generic `extension` escape hatch "
        "anymore. See the [operations guide](operations.md).",
        "- `connector list-secret` is the only command that can return "
        "connector secret material in plain text; everything else "
        "(`connector show`, `connector list`, `connector create`/`update` "
        "responses) redacts secret fields server-side.",
        "",
        "## Global options",
        "",
        "These Azure CLI global options apply to every command and are not "
        "repeated in each syntax line.",
        "",
        "| Option | Description |",
        "| --- | --- |",
    ]
    lines.extend(f"| `{option}` | {_cell(description)} |" for option, description in GLOBAL_OPTIONS)

    for group_name in sorted(groups, key=lambda value: (value.count(" "), value)):
        group_help = groups[group_name]["help"] or {}
        lines.extend(["", f"## `az {group_name}`", "", _cell(group_help.get("short-summary"))])
        long_summary = _cell(group_help.get("long-summary"))
        if long_summary:
            lines.extend(["", long_summary])

        child_groups = _direct_children(group_name, groups)
        if child_groups:
            lines.extend(["", "| Subgroup | Summary |", "| --- | --- |"])
            for child in child_groups:
                child_help = groups[child]["help"] or {}
                lines.append(
                    f"| `{child.removeprefix(group_name + ' ')}` | "
                    f"{_cell(child_help.get('short-summary'))} |"
                )

        child_commands = _direct_children(group_name, commands)
        if child_commands:
            lines.extend(["", "| Verb | Exact syntax |", "| --- | --- |"])
            for command_name in child_commands:
                command = commands[command_name]
                lines.append(
                    f"| `{command_name.removeprefix(group_name + ' ')}` | "
                    f"`{command_syntax(command_name, command['options'])}` |"
                )

        for command_name in child_commands:
            command = commands[command_name]
            help_data = command["help"] or {}
            lines.extend(
                ["", f"### `az {command_name}`", "", _cell(help_data.get("short-summary"))]
            )
            long_summary = _cell(help_data.get("long-summary"))
            if long_summary:
                lines.extend(["", long_summary])
            lines.extend(["", "**Syntax**", "", f"`{command_syntax(command_name, command['options'])}`"])
            if command["options"]:
                lines.extend(
                    [
                        "",
                        "| Option / aliases | Type | Required | Default | "
                        "Allowed values | Description |",
                        "| --- | --- | --- | --- | --- | --- |",
                    ]
                )
                for option in command["options"]:
                    aliases = ", ".join(f"`{alias}`" for alias in option.aliases)
                    choices = ", ".join(f"`{choice}`" for choice in option.choices)
                    lines.append(
                        f"| {aliases} | {option.kind} | "
                        f"{'Yes' if option.required else 'No'} | "
                        f"{_cell(option.default)} | {choices} | {_cell(option.help)} |"
                    )
            examples = help_data.get("examples") or []
            if examples:
                lines.extend(["", "**Examples**", ""])
                for example in examples:
                    lines.extend(
                        [f"- {_cell(example.get('name'))}", "", f"  `{_cell(example.get('text'))}`"]
                    )

    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate the az sre CLI ergonomics reference.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail instead of writing when the committed reference is stale.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    root = repository_root()
    path = root / REFERENCE_PATH
    expected = render_reference()
    current = path.read_text() if path.exists() else None
    if args.check:
        if current != expected:
            print(f"{REFERENCE_PATH} is stale; run '{REGENERATION_COMMAND}'.", file=sys.stderr)
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
